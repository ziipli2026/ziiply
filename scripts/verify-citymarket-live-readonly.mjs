import { neon } from '@neondatabase/serverless';
import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';

const url=process.env.DATABASE_URL;
if(!url) throw Error('Read-only Neon DATABASE_URL missing');
const sql=neon(url);
const permission=await sql`SELECT current_user AS role, has_table_privilege(current_user,'public.ziiply_kcitymarket_tjek_snapshots','INSERT') AS can_insert, has_table_privilege(current_user,'public.ziiply_kcitymarket_tjek_snapshots','UPDATE') AS can_update, has_table_privilege(current_user,'public.ziiply_kcitymarket_tjek_snapshots','DELETE') AS can_delete`;
assert.ok(permission.length,'Role permission check unavailable');
assert.equal(permission[0].can_insert,false,'Connection is NOT read-only (INSERT privilege)');
assert.equal(permission[0].can_update,false,'Connection is NOT read-only (UPDATE privilege)');
assert.equal(permission[0].can_delete,false,'Connection is NOT read-only (DELETE privilege)');
const data=await sql`SELECT offers,updated_at,valid_until,publication_ids FROM public.ziiply_kcitymarket_tjek_snapshots WHERE store_key='k citymarket hyvinkaa' ORDER BY updated_at DESC LIMIT 1`;
assert.equal(data.length,1,'Missing selected-store snapshot');
const snapshot=data[0];
assert.ok(new Date(snapshot.valid_until).getTime()>Date.now(),'Snapshot expired');
assert.ok(Array.isArray(snapshot.offers)&&snapshot.offers.length>0,'Empty snapshot');
const source=fs.readFileSync('src/app/components/ziiply/offerSearch/tjekDepartmentCategory.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};vm.runInNewContext(js,{exports});
const rows=snapshot.offers;
const eligible=exports.normalizeTjekGroceryCategories(rows);
const ids=eligible.map(r=>String(r.offerId??r.id??''));
assert.ok(ids.every(Boolean),'Missing offer ID');
assert.equal(new Set(ids).size,ids.length,'Duplicate offer IDs');
assert.ok(eligible.every(r=>Number(r.price)>0),'Missing/invalid offer price');
assert.ok(eligible.every(r=>r.validFrom&&r.validUntil),'Missing offer validity');
assert.ok(eligible.every(r=>r.category&&r.category!=='Muut'),'Uncategorized live offers');
assert.ok(eligible.every(r=>r.debug?.tjekDepartmentSlug),'Missing Tjek department');
const excluded=rows.filter(r=>!eligible.some(e=>e===r||String(e.offerId)===String(r.offerId)));
console.log('CITYMARKET_LIVE_READONLY_OK',JSON.stringify({snapshotUpdatedAt:snapshot.updated_at,sourceCount:rows.length,eligibleCount:eligible.length,excludedCount:excluded.length,excludedTitles:excluded.map(x=>x.title),categories:[...new Set(eligible.map(x=>x.category))].sort()}));

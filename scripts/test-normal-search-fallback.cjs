const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const ts = require("typescript");
const source = readFileSync("src/lib/normalSearchFallback.ts", "utf8");
const js = ts.transpileModule(source.replaceAll("export function", "function"), { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
const getZeroResultFallbackQuery = new Function(js + "; return getZeroResultFallbackQuery;")();
assert.equal(getZeroResultFallbackQuery("Oltermanni alkuperäinen 1kg"), "Oltermanni alkuperäinen");
assert.equal(getZeroResultFallbackQuery("Santa Maria tortilla original 8kpl"), "Santa Maria tortilla original");
assert.equal(getZeroResultFallbackQuery("Santa Maria tortilla"), null);
assert.equal(getZeroResultFallbackQuery("Valio PROfeel proteiinivanukas suklaa"), null);
assert.equal(getZeroResultFallbackQuery("Pirkka täysjyvävehnätortilla 8 kpl 320g"), "Pirkka täysjyvävehnätortilla 8 kpl");
console.log("Zero-result fallback query tests passed");

const normalizeSearchPackageSpacing = new Function(js + "; return normalizeSearchPackageSpacing;")();
assert.equal(getZeroResultFallbackQuery("Oltermanni alkuperäinen 1 kg"), "Oltermanni alkuperäinen");
assert.equal(getZeroResultFallbackQuery("Oltermanni alkuperäinen 0,5 kg"), "Oltermanni alkuperäinen");
assert.equal(getZeroResultFallbackQuery("Santa Maria tortilla original 8 kpl"), "Santa Maria tortilla original");
assert.equal(getZeroResultFallbackQuery("maito 1 kg"), null);
assert.equal(normalizeSearchPackageSpacing("Oltermanni alkuperäinen 1kg"), normalizeSearchPackageSpacing("Oltermanni alkuperäinen 1 kg"));
assert.equal(normalizeSearchPackageSpacing("Valio Oltermanni e1 kg"), "Valio Oltermanni 1kg");
assert.notEqual(normalizeSearchPackageSpacing("Oltermanni 1 kg"), normalizeSearchPackageSpacing("Oltermanni 500 g"));
console.log("Package spacing regression tests passed");

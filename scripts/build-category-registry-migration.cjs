#!/usr/bin/env node
// Generate a reproducible test-only migration from the registry used by search.
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('src/app/components/ziiply/search/searchCategoryRegistry.ts', 'utf8');
const section = source.split('export const SEARCH_INTENTS: SearchIntent[] = ')[1];
const rules = vm.runInNewContext(section.replace(/;\s*$/, ''));
const mappings = JSON.parse(fs.readFileSync('data/search/category-mappings-reviewed.json', 'utf8'));
const exceptions = JSON.parse(fs.readFileSync('data/search/product-category-exceptions-reviewed.json', 'utf8')).exceptions;
for (const row of exceptions) {
  if (!/^\d{13}$/.test(row.ean) || ([...row.ean.slice(0,12)].reduce((sum,digit,index)=>sum+Number(digit)*(index%2?3:1),0)+Number(row.ean[12]))%10) throw Error('Invalid reviewed EAN '+row.ean);
  if (!rules.some(rule=>rule.category===row.category_id)) throw Error('Unknown exception category '+row.category_id);
}
const normalize = value => value.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, ' ').trim();
const quote = value => "'" + String(value).replace(/'/g, "''") + "'";
const statements = [
  'ALTER TABLE ziiply_product_categories ADD COLUMN IF NOT EXISTS search_rules jsonb',
  'ALTER TABLE ziiply_product_categories ADD COLUMN IF NOT EXISTS registry_version text',
];
for (const rule of rules) {
  statements.push(`INSERT INTO ziiply_product_categories(id,label_fi,status,search_rules,registry_version) VALUES (${quote(rule.category)},${quote(rule.label)},'active',${quote(JSON.stringify(rule))}::jsonb,${quote(mappings.version)}) ON CONFLICT(id) DO UPDATE SET label_fi=EXCLUDED.label_fi,status=EXCLUDED.status,search_rules=EXCLUDED.search_rules,registry_version=EXCLUDED.registry_version`);
  const seen = new Set();
  for (const term of rule.variants) {
    const normalized = normalize(term);
    if (seen.has(normalized)) continue;
    seen.add(normalized);
    statements.push(`INSERT INTO ziiply_search_synonyms(category_id,term,term_normalized,status) VALUES (${quote(rule.category)},${quote(term)},${quote(normalized)},'active') ON CONFLICT(category_id,term_normalized) DO UPDATE SET term=EXCLUDED.term,status=EXCLUDED.status`);
  }
}
for (const rule of rules) if (rule.parentCategory) statements.push(`UPDATE ziiply_product_categories SET parent_id=${quote(rule.parentCategory)} WHERE id=${quote(rule.category)}`);
statements.push("UPDATE ziiply_search_synonyms SET status='draft' WHERE category_id='frozen' AND term_normalized IN ('jaatelo','pakastevihannekset')");
statements.push("UPDATE ziiply_search_synonyms SET status='draft' WHERE category_id='milk' AND term_normalized='kauramaito'");
for (const row of mappings.mappings) statements.push(`UPDATE ziiply_source_category_mappings SET ziiply_category_id=${quote(row.category_id)},review_status='reviewed',updated_at=now() WHERE source=${quote(row.source)} AND source_category=${quote(row.source_category)}`);
for (const row of exceptions) statements.push(`INSERT INTO ziiply_product_category_exceptions(ean,source,source_category,proposed_category_id,reason,review_status) VALUES (${quote(row.ean)},${quote(row.source)},${quote(row.source_category)},${quote(row.category_id)},${quote(row.reason)},'reviewed') ON CONFLICT(ean,source,source_category) DO UPDATE SET proposed_category_id=EXCLUDED.proposed_category_id,reason=EXCLUDED.reason,review_status=EXCLUDED.review_status`);
const snapshot = JSON.stringify({version:mappings.version,projectId:mappings.projectId,branchId:mappings.branchId,rules},null,2)+'\n';
const sql = '-- Apply only to Neon branch '+mappings.branchId+'. Search consumes the same versioned rules.\nBEGIN;\n'+statements.join(';\n')+';\nCOMMIT;\n';
const mappingModule = `// Generated by scripts/build-category-registry-migration.cjs; version ${mappings.version}.
import type { SearchIntentCategory } from "../ziiplyCore";
import { SEARCH_INTENTS } from "./searchCategoryRegistry";
const reviewedMappings: { source_category: string; category_id: SearchIntentCategory }[] = ${JSON.stringify(mappings.mappings.filter(row => row.allowGlobalMatch !== false).map(({source_category,category_id})=>({source_category,category_id})),null,2)};
const categories = new Map<string, Set<SearchIntentCategory>>();
for (const row of reviewedMappings) {
  const ids = categories.get(row.source_category) || new Set<SearchIntentCategory>();
  ids.add(row.category_id);
  categories.set(row.source_category, ids);
}
// A parent query accepts its descendants; a child query remains specific.
export function isReviewedCategoryCompatible(query: SearchIntentCategory, product: SearchIntentCategory): boolean {
  const seen = new Set<SearchIntentCategory>();
  const pending: SearchIntentCategory[] = [product];
  while (pending.length) {
    const current = pending.pop()!;
    if (current === query) return true;
    if (seen.has(current)) continue;
    seen.add(current);
    const rule = SEARCH_INTENTS.find(rule => rule.category === current);
    pending.push(...(rule?.parentCategories || (rule?.parentCategory ? [rule.parentCategory] : [])));
  }
  return false;
}
// Broad and unknown provider categories remain inconclusive.
export function getReviewedProductCategory(category?: string): SearchIntentCategory | undefined {
  const ids = categories.get(category?.trim() || "");
  return ids?.size === 1 ? [...ids][0] : undefined;
}
`;
const exceptionModule = `// Generated by scripts/build-category-registry-migration.cjs; version ${mappings.version}.
import type { SearchIntentCategory } from "../ziiplyCore";
const reviewedExceptions: { ean: string; category_id: SearchIntentCategory }[] = ${JSON.stringify(exceptions.map(({ean,category_id})=>({ean,category_id})),null,2)};
const categories = new Map<string, Set<SearchIntentCategory>>();
for (const row of reviewedExceptions) {
  const ids = categories.get(row.ean) || new Set<SearchIntentCategory>();
  ids.add(row.category_id);
  categories.set(row.ean, ids);
}
// EAN identifies the product even when its provider category is incorrect.
export function getReviewedEanCategory(ean?: string): SearchIntentCategory | undefined {
  const ids = categories.get(ean?.trim() || "");
  return ids?.size === 1 ? [...ids][0] : undefined;
}
`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync('data/search/category-registry-reviewed.json','utf8') !== snapshot || fs.readFileSync('scripts/sql/ziiply-category-registry-reviewed.sql','utf8') !== sql) throw Error('Registry snapshot or migration is stale');
  if (fs.readFileSync('src/app/components/ziiply/search/reviewedCategoryMappings.ts','utf8') !== mappingModule) throw Error('Compiled category mappings are stale');
  if (fs.readFileSync('src/app/components/ziiply/search/reviewedProductCategoryExceptions.ts','utf8') !== exceptionModule) throw Error('Compiled product exceptions are stale');
} else {
  fs.writeFileSync('data/search/category-registry-reviewed.json', snapshot);
  fs.writeFileSync('scripts/sql/ziiply-category-registry-reviewed.sql',sql);
  fs.writeFileSync('src/app/components/ziiply/search/reviewedCategoryMappings.ts',mappingModule);
  fs.writeFileSync('src/app/components/ziiply/search/reviewedProductCategoryExceptions.ts',exceptionModule);
}
console.log(JSON.stringify({groups:rules.length,reviewedMappings:mappings.mappings.length,version:mappings.version}));

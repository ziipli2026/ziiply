const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const vm=require('node:vm');
const source=fs.readFileSync('src/app/components/ziiplyRequestRecovery.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
const testModule={exports:{}};
vm.runInNewContext(js,{module:testModule,exports:testModule.exports});
const {registerZiiplyRecoverableRequest:register,recoverZiiplyStalledRequests:recover}=testModule.exports;
let aborted=0,retried=0;
const unregister=register('offers',{kind:'offer-search',startedAt:100,abort:()=>aborted++,recover:()=>retried++});
register('fresh',{kind:'product-search',startedAt:39_000,abort:()=>aborted++});
assert.equal(recover(40_000),1);
assert.equal(aborted,1);
assert.equal(retried,1);
assert.equal(recover(40_001),0,'stale requests are recovered only once');
unregister();
assert.equal(recover(70_000),1);
assert.equal(aborted,2);
console.log('PASS: registered stale requests recover, fresh requests survive, duplicate recovery suppressed');

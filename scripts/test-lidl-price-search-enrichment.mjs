import assert from "node:assert/strict";
import { enrichLidlResearchWithVerifiedPrices as enrich } from "./lib/lidl-price-search-enrichment.mjs";
const at=new Date("2026-10-04T12:00:00Z");
const items=[{lidlProductId:"123",name:"Synthetic test product",price:null,observedPriceEur:0.89,historicalAnnouncedPriceEur:0.79},{lidlProductId:"456",name:"Other synthetic product",price:null}];
const row={lidlProductId:"123",storeId:"store-A",regularPriceEur:1.29,priceKind:"regular",priceSource:"verified-store-receipt",checkoutPriceVerified:true,evidenceReference:"SYNTHETIC-NOT-REAL",observedAt:"2026-10-04T10:00:00Z",validThrough:null};
const empty=enrich(items,[],"store-A",at);
assert.equal(empty.items[0].price,null);
assert.equal(empty.items[0].priceVerified,false);
assert.equal(empty.items[0].historicalAnnouncedPriceEur,0.79);
const wrong=enrich(items,[{...row,storeId:"store-B"}],"store-A",at);
assert.equal(wrong.items[0].price,null);
const verified=enrich(items,[row],"store-A",at);
assert.equal(verified.items[0].price,1.29);
assert.equal(verified.items[0].priceVerified,true);
assert.equal(verified.items[0].storeItems[0].storeId,"store-A");
assert.equal(verified.items[0].verifiedPriceEvidence.validThrough,null);
assert.equal(verified.items[0].verifiedPriceEvidence.freshUntil,"2026-10-05T10:00:00.000Z");
assert.equal(verified.items[1].price,null);
const stale=enrich(items,[row],"store-A",new Date("2026-10-06T12:00:00Z"));
assert.equal(stale.items[0].price,null);
console.log("PASS: research results enriched only by valid, matching-store checkout evidence");
